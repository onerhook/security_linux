#!/bin/bash
# =============================================================================
# RedSand Secure - Docker Entrypoint Script
# Максимальная безопасность при запуске контейнера
# =============================================================================

set -euo pipefail

# Цвета для вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${BLUE}[INFO]${NC} $(date '+%Y-%m-%d %H:%M:%S') - $1"
}

log_success() {
    echo -e "${GREEN}[OK]${NC} $(date '+%Y-%m-%d %H:%M:%S') - $1"
}

log_warning() {
    echo -e "${YELLOW}[WARN]${NC} $(date '+%Y-%m-%d %H:%M:%S') - $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $(date '+%Y-%m-%d %H:%M:%S') - $1"
}

# =============================================================================
# Security Check 1: Проверка пользователя
# =============================================================================
log_info "Проверка пользователя..."
if [ "$(id -u)" = "0" ]; then
    log_error "Запуск от root запрещен! Используйте non-root пользователя."
    exit 1
fi
log_success "Запуск от пользователя: $(whoami) (UID: $(id -u))"

# =============================================================================
# Security Check 2: Проверка прав доступа к директориям
# =============================================================================
log_info "Проверка прав доступа к директориям..."

for dir in /app/logs /app/reports /app/quarantine /app/samples /app/config /app/cache; do
    if [ -d "$dir" ]; then
        if [ ! -w "$dir" ] && [[ "$dir" != *"/samples" ]] && [[ "$dir" != *"/config" ]]; then
            log_warning "Нет прав на запись в $dir (это может быть нормально для read-only mounts)"
        else
            log_success "Директория $dir доступна"
        fi
    else
        log_warning "Директория $dir не существует"
    fi
done

# =============================================================================
# Security Check 3: Проверка переменных окружения безопасности
# =============================================================================
log_info "Проверка переменных окружения безопасности..."

# Проверка критических переменных
if [ "${REDSAND_SECURITY_LEVEL:-}" != "maximum" ]; then
    log_warning "REDSAND_SECURITY_LEVEL не установлен в 'maximum'"
fi

if [ "${SECURE_MODE:-}" != "true" ]; then
    log_warning "SECURE_MODE не установлен в 'true'"
fi

# Проверка на опасные переменные
if [ -n "${PYTHONINSPECT:-}" ]; then
    log_error "Обнаружена опасная переменная PYTHONINSPECT!"
    unset PYTHONINSPECT
fi

if [ -n "${PYTHONBREAKPOINT:-}" ]; then
    log_warning "Переменная PYTHONBREAKPOINT установлена. Сбрасываем."
    unset PYTHONBREAKPOINT
fi

log_success "Переменные окружения проверены"

# =============================================================================
# Security Check 4: Очистка временных файлов
# =============================================================================
log_info "Очистка временных файлов..."
rm -rf /tmp/* 2>/dev/null || true
rm -rf /var/tmp/* 2>/dev/null || true
mkdir -p /tmp /var/tmp
chmod 1777 /tmp /var/tmp
log_success "Временные файлы очищены"

# =============================================================================
# Security Check 5: Проверка сетевых настроек
# =============================================================================
log_info "Проверка сетевых настроек..."

if [ "${NETWORK_ENABLED:-false}" = "false" ]; then
    # Блокируем весь исходящий трафик на уровне iptables если сеть отключена
    if command -v iptables &> /dev/null; then
        log_info "Блокировка сетевого трафика..."
        iptables -P OUTPUT DROP 2>/dev/null || true
        iptables -P FORWARD DROP 2>/dev/null || true
        # Разрешаем только loopback
        iptables -A OUTPUT -o lo -j ACCEPT 2>/dev/null || true
        log_success "Сетевой трафик заблокирован"
    fi
else
    log_warning "Сеть включена! Это снижает уровень безопасности."
fi

# =============================================================================
# Security Check 6: Установка лимитов ресурсов
# =============================================================================
log_info "Настройка лимитов ресурсов..."

# Устанавливаем ulimit если возможно
ulimit -n 1024 2>/dev/null || log_warning "Не удалось установить лимит на открытые файлы"
ulimit -u 50 2>/dev/null || log_warning "Не удалось установить лимит на процессы"
ulimit -v 524288 2>/dev/null || log_warning "Не удалось установить лимит на память"

log_success "Лимиты ресурсов настроены"

# =============================================================================
# Security Check 7: Аудит системных вызовов (если доступен auditd)
# =============================================================================
if [ "${PYTHONAUDIT:-0}" = "1" ]; then
    log_info "Включен аудит Python..."
    export PYTHONAUDIT=1
fi

# =============================================================================
# Security Check 8: Создание карантинной директории с правильными правами
# =============================================================================
log_info "Настройка карантинной директории..."
if [ -d "/app/quarantine" ]; then
    chmod 750 /app/quarantine
    chown "$(id -un):$(id -gn)" /app/quarantine
    log_success "Карантинная директория настроена"
fi

# =============================================================================
# Security Check 9: Логирование информации о системе
# =============================================================================
log_info "Информация о системе:"
log_info "  OS: $(uname -a 2>/dev/null || echo 'N/A')"
log_info "  Python: $(python --version 2>&1 || echo 'N/A')"
log_info "  Hostname: $(hostname 2>/dev/null || echo 'N/A')"
log_info "  UID/GID: $(id 2>/dev/null || echo 'N/A')"

# =============================================================================
# Security Check 10: Предупреждение о запуске
# =============================================================================
echo ""
echo "============================================================================="
echo "  RedSand Secure v3.0 - Максимально защищенный режим"
echo "============================================================================="
echo "  ⚠️  ВНИМАНИЕ: Система работает в изолированной среде"
echo "  📁 Samples:     /app/samples (read-only)"
echo "  📊 Reports:     /app/reports"
echo "  🦠 Quarantine:  /app/quarantine"
echo "  📝 Logs:        /app/logs"
echo "  🔒 Security:    ${REDSAND_SECURITY_LEVEL:-standard}"
echo "  🌐 Network:     ${NETWORK_ENABLED:-false}"
echo "  👤 User:        $(whoami) (UID: $(id -u))"
echo "============================================================================="
echo ""

# =============================================================================
# Запуск основного приложения
# =============================================================================
log_info "Запуск RedSand Secure..."

# Проверяем, переданы ли аргументы
if [ $# -eq 0 ]; then
    # Аргументов нет - показываем помощь
    exec python redsand_secure.py --help
else
    # Запускаем с переданными аргументами
    exec "$@"
fi
