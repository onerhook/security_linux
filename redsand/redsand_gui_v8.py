class ThreatAnalyzer:
    """
    Реальный анализатор угроз с защитой от ложных срабатываний.
    """
    
    # Опасные расширения (исполняемые файлы)
    DANGEROUS_EXTENSIONS = {'.exe', '.dll', '.sys', '.bat', '.cmd', '.ps1', '.vbs', '.js', '.msi', '.scr'}
    
    # Подозрительные расширения (скрипты, документы с макросами)
    SUSPICIOUS_EXTENSIONS = {'.py', '.pyw', '.docm', '.xlsm', '.pptm', '.hta', '.wsf'}
    
    # Критические API для Windows исполняемых файлов
    CRITICAL_APIS = [
        'VirtualAllocEx', 'WriteProcessMemory', 'CreateRemoteThread',
        'NtUnmapViewOfSection', 'SetWindowsHookEx', 'GetAsyncKeyState',
        'URLDownloadToFile', 'WinExec', 'ShellExecute', 'CryptEncrypt',
        'RegSetValueEx', 'CreateService', 'OpenProcess'
    ]
    
    # Индикаторы конкретных угроз
    THREAT_INDICATORS = {
        'RANSOMWARE': [b'your files are encrypted', b'bitcoin', b'ransom', b'decrypt', b'wallet'],
        'STEALER': [b'steal', b'password', b'cookie', b'token', b'credential', b'keylog'],
        'BACKDOOR': [b'backdoor', b'reverse shell', b'c2 server', b'command and control', b'beacon'],
        'TROJAN': [b'trojan', b'dropper', b'downloader', b'payload'],
        'MINER': [b'miner', b'stratum', b'coinhive', b'monero', b'xmr'],
        'ROOTKIT': [b'rootkit', b'hide process', b'hook ssdt', b'kernel mode'],
        'WORM': [b'worm', b'spread', b'network share', b'replication'],
        'ADWARE': [b'adware', b'popup', b'banner', b'redirect'],
        'SPYWARE': [b'spy', b'screenshot', b'microphone', b'webcam', b'surveillance']
    }
    
    # Белый список безопасных строк (снижает риск)
    SAFE_STRINGS = [
        b'copyright', b'license', b'mit', b'apache', b'gnu', b'version',
        b'author', b'email', b'description', b'python', b'import',
        b'def ', b'class ', b'print(', b'if __name__', b'# -*- coding',
        b'microsoft', b'corporation', b'all rights reserved',
        b'generated by', b'compiler', b'build', b'source'
    ]

    def __init__(self):
        self.results = []
        self.threats_found = []
        self.safe_score = 0
        self.danger_score = 0

    def analyze_file(self, file_path: str) -> Dict[str, Any]:
        """Полный анализ файла."""
        self.results = []
        self.threats_found = []
        self.safe_score = 0
        self.danger_score = 0
        
        path = Path(file_path)
        
        if not path.exists():
            return {"error": "File not found"}
        
        # 1. Базовая информация
        file_size = path.stat().st_size
        file_ext = path.suffix.lower()
        
        self._log_info(f"Анализ файла: {path.name}")
        self._log_info(f"Размер: {file_size} байт")
        self._log_info(f"Расширение: {file_ext}")
        
        # 2. Проверка расширений
        self._check_extension(file_ext)
        
        # 3. Чтение содержимого (первые 1MB для скорости)
        try:
            with open(file_path, 'rb') as f:
                content = f.read(1024 * 1024)
            
            # 4. Проверка Magic Bytes
            self._check_magic_bytes(content, file_ext)
            
            # 5. Поиск опасных строк и API
            self._check_content(content, file_ext)
            
            # 6. Оценка безопасности (белый список)
            self._check_safe_strings(content)
            
        except Exception as e:
            self._log_error(f"Ошибка чтения файла: {str(e)}")
        
        # 7. Финальный вердикт
        verdict = self._calculate_verdict()
        
        return {
            "file": str(path),
            "size": file_size,
            "extension": file_ext,
            "threats": self.threats_found,
            "threat_count": len(self.threats_found),
            "verdict": verdict["verdict"],
            "risk_level": verdict["risk"],
            "details": self.results
        }

    def _log_info(self, msg: str):
        self.results.append({"type": "INFO", "message": msg, "severity": "low"})

    def _log_warning(self, msg: str):
        self.results.append({"type": "WARNING", "message": msg, "severity": "medium"})
        self.danger_score += 5

    def _log_danger(self, msg: str, threat_type: str = None):
        # Проверяем, нет ли уже такой угрозы (защита от дублей)
        if threat_type:
            for t in self.threats_found:
                if t.get('name') == threat_type:
                    return  # Уже есть такая угроза
        
        self.results.append({"type": "DANGER", "message": msg, "severity": "high"})
        self.danger_score += 20
        if threat_type:
            self.threats_found.append({"name": threat_type, "reason": msg})

    def _check_extension(self, ext: str):
        """Проверка расширения файла."""
        if ext in self.DANGEROUS_EXTENSIONS:
            self._log_warning(f"Подозрительное расширение: {ext} (исполняемый файл)")
        elif ext in self.SUSPICIOUS_EXTENSIONS:
            # Для .py это нормально, просто предупреждение
            if ext == '.py':
                self._log_info("Файл является Python скриптом. Требуется проверка кода.")
            else:
                self._log_warning(f"Расширение может содержать макросы: {ext}")

    def _check_magic_bytes(self, content: bytes, ext: str):
        """Проверка сигнатур файла."""
        if len(content) < 4:
            return
            
        # MZ заголовок (PE файл)
        if content[:2] == b'MZ':
            if ext != '.exe' and ext != '.dll':
                self._log_danger("Несоответствие расширения и содержимого (PE файл)", "MASQUERADE")
            else:
                self._log_info("Обнаружен PE формат (Windows Executable)")
        
        # ELF (Linux)
        elif content[:4] == b'\x7fELF':
            self._log_info("Обнаружен ELF формат (Linux Executable)")
            
        # PDF
        elif content[:4] == b'%PDF':
            self._log_info("Обнаружен PDF документ")
            
        # ZIP/Office
        elif content[:2] == b'PK':
            self._log_info("Обнаружен ZIP архив или Office документ")

    def _check_content(self, content: bytes, ext: str):
        """Поиск опасных паттернов."""
        
        # Ищем критические API только в бинарных файлах или если это скрипт
        # Но игнорируем импорты в Python коде, если это не обфускация
        if ext in ['.exe', '.dll', '.sys']:
            for api in self.CRITICAL_APIS:
                if api.encode() in content:
                    self._log_warning(f"Обнаружен опасный API: {api}")
        
        # Поиск индикаторов угроз
        for threat_type, indicators in self.THREAT_INDICATORS.items():
            matches = 0
            for indicator in indicators:
                if indicator in content.lower():
                    matches += 1
            
            # Угроза считается подтвержденной только при множественных совпадениях
            if matches >= 2:
                self._log_danger(f"Найдены индикаторы типа {threat_type} ({matches} совпадений)", threat_type)
            elif matches == 1:
                # Единичное совпадение - просто предупреждение, а не угроза
                self._log_warning(f"Возможный индикатор {threat_type} (требуется проверка)")

    def _check_safe_strings(self, content: bytes):
        """Проверка на признаки легитимного ПО."""
        content_lower = content.lower()
        safe_matches = 0
        
        for safe in self.SAFE_STRINGS:
            if safe in content_lower:
                safe_matches += 1
        
        if safe_matches > 3:
            self.safe_score += safe_matches * 10
            self._log_info(f"Найдено признаков легитимного ПО: {safe_matches}")

    def _calculate_verdict(self) -> Dict[str, str]:
        """Расчет финального вердикта."""
        # Если файл легитимный (много safe строк) и мало угроз
        if self.safe_score > 30 and self.danger_score < 20:
            return {"verdict": "CLEAN", "risk": "0%"}
        
        # Если найдены реальные угрозы
        if len(self.threats_found) > 0:
            risk = min(100, 20 + len(self.threats_found) * 15 + self.danger_score)
            return {"verdict": "MALICIOUS", "risk": f"{risk}%"}
        
        # Если есть подозрения, но нет явных угроз
        if self.danger_score > 15:
            return {"verdict": "SUSPICIOUS", "risk": f"{min(60, self.danger_score)}%"}
        
        return {"verdict": "CLEAN", "risk": "0%"}


