    def browse_file(self):
        file_path, _ = QFileDialog.getOpenFileName(self, "Выберите файл", "", "All Files (*)")
        if file_path:
            self.current_file = file_path
            self.file_path_edit.setText(file_path)
            self.log_message(f"[INFO] Выбран файл: {file_path}")
            
    def change_language(self, index):
        # Заглушка для переключения языка
        lang = "Русский" if index == 0 else "English"
        self.log_message(f"[INFO] Язык изменен на: {lang}")
        # Здесь должна быть полная реализация перевода
        
    def log_message(self, msg: str):
        timestamp = datetime.now().strftime("%H:%M:%S")
        self.log_view.appendPlainText(f"[{timestamp}] {msg}")
        self.log_view.verticalScrollBar().setValue(self.log_view.verticalScrollBar().maximum())
        
    def start_scan(self):
        if not self.current_file:
            QMessageBox.warning(self, "Ошибка", "Сначала выберите файл!")
            return
            
        self.is_scanning = True
        self.scan_btn.setEnabled(False)
        self.stop_btn.setEnabled(True)
        self.progress_bar.setValue(0)
        self.results_table.setRowCount(0)
        self.log_view.clear()
        
        self.log_message("[INFO] Начало сканирования...")
        self.status_label.setText("Статус: Сканирование...")
        
        # Запуск в потоке
        self.thread = Thread(target=self.run_scan)
        self.thread.start()
        
        # Анимация прогресса
        self.timer = QTimer()
        self.timer.timeout.connect(self.update_progress)
        self.timer.start(50)
        
    def run_scan(self):
        results = self.analyzer.analyze_file(self.current_file)
        
        # Обновление UI в главном потоке
        QTimer.singleShot(0, lambda: self.finish_scan(results))
        
    def update_progress(self):
        val = self.progress_bar.value()
        if val < 90:
            self.progress_bar.setValue(val + 5)
            
    def finish_scan(self, results):
        self.timer.stop()
        self.progress_bar.setValue(100)
        self.is_scanning = False
        self.scan_btn.setEnabled(True)
        self.stop_btn.setEnabled(False)
        
        # Отображение результатов
        verdict = results.get('verdict', 'UNKNOWN')
        risk = results.get('risk_level', '0%')
        threats = results.get('threats', [])
        
        self.status_label.setText(f"Статус: Завершено. Вердикт: {verdict}")
        
        # Цвет вердикта
        color = "#2ed573" if verdict == "CLEAN" else ("#ffa502" if verdict == "SUSPICIOUS" else "#ff4757")
        self.status_label.setStyleSheet(f"font-weight: bold; color: {color}; font-size: 14px;")
        
        self.log_message(f"[RESULT] Вердикт: {verdict}, Риск: {risk}")
        self.log_message(f"[RESULT] Найдено угроз: {len(threats)}")
        
        # Заполнение таблицы
        details = results.get('details', [])
        self.results_table.setRowCount(len(details))
        
        for i, item in enumerate(details):
            type_item = QTableWidgetItem(item['type'])
            msg_item = QTableWidgetItem(item['message'])
            sev_item = QTableWidgetItem(item['severity'])
            
            # Цвета для типов
            if item['type'] == 'DANGER':
                type_item.setForeground(QColor("#ff4757"))
            elif item['type'] == 'WARNING':
                type_item.setForeground(QColor("#ffa502"))
            else:
                type_item.setForeground(QColor("#2ed573"))
                
            self.results_table.setItem(i, 0, type_item)
            self.results_table.setItem(i, 1, msg_item)
            self.results_table.setItem(i, 2, sev_item)
            
        # Финальное окно
        msg = f"Вердикт: {verdict}\nУровень риска: {risk}\nНайдено угроз: {len(threats)}\n\n"
        if threats:
            msg += "Обнаруженные угрозы:\n" + "\n".join([f"- {t['name']}: {t['reason']}" for t in threats])
        else:
            msg += "Детальных угроз не найдено. Файл считается безопасным."
            
        QMessageBox.information(self, "Результаты сканирования", msg)

    def stop_scan(self):
        self.is_scanning = False
        self.timer.stop()
        self.scan_btn.setEnabled(True)
        self.stop_btn.setEnabled(False)
        self.status_label.setText("Статус: Остановлено пользователем")
        self.log_message("[WARNING] Сканирование остановлено.")


